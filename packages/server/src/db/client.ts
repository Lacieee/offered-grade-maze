/**
 * PostgreSQL connection and migrations (CP07 T2). Migrations run at server start, before
 * the server listens.
 */
import { fileURLToPath } from 'node:url';
import { drizzle, type NodePgDatabase } from 'drizzle-orm/node-postgres';
import { migrate } from 'drizzle-orm/node-postgres/migrator';
import { sql } from 'drizzle-orm';
import pg from 'pg';
import * as schema from './schema.js';

/** The Drizzle database handle used by the services. */
export type Db = NodePgDatabase<typeof schema>;

/** A connection pool and its Drizzle handle. */
export interface Database {
  db: Db;
  pool: pg.Pool;
  close(): Promise<void>;
}

/** SQL migrations generated by drizzle-kit (`packages/server/drizzle`, next to `src`/`dist`). */
export const MIGRATIONS_DIR = fileURLToPath(new URL('../../drizzle', import.meta.url));

/** Opens a pool on `url`. */
export function openDatabase(url: string, max = 10): Database {
  const pool = new pg.Pool({ connectionString: url, max });
  // An idle client losing its connection must not crash the process.
  pool.on('error', () => undefined);
  return {
    db: drizzle(pool, { schema }),
    pool,
    close: () => pool.end(),
  };
}

/** Applies every pending migration. */
export async function runMigrations(db: Db): Promise<void> {
  await migrate(db, { migrationsFolder: MIGRATIONS_DIR });
}

/** True if the database answers a trivial query within `timeoutMs`. */
export async function pingDatabase(db: Db, timeoutMs = 1000): Promise<boolean> {
  let timer: NodeJS.Timeout | undefined;
  try {
    const timeout = new Promise<never>((_, reject) => {
      timer = setTimeout(() => {
        reject(new Error('timeout'));
      }, timeoutMs);
    });
    await Promise.race([db.execute(sql`select 1`), timeout]);
    return true;
  } catch {
    return false;
  } finally {
    clearTimeout(timer);
  }
}
